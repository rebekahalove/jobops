import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = findRepoRoot(dirname(fileURLToPath(import.meta.url)));
loadEnvFile(join(repoRoot, ".env"));

const appEnv = process.env.APP_ENV;
if (appEnv && /^[A-Za-z0-9_-]+$/.test(appEnv)) {
  loadEnvFile(join(repoRoot, `.env.${appEnv}`));
}

const metadata = {
  appName: "JobOps",
  releaseChannel: "alpha",
  environment: resolveEnvironment(),
  commit: shortCommit(resolveCommit()),
  fullCommit: safeCommit(resolveCommit()),
  buildTime: new Date().toISOString()
};

if (!metadata.fullCommit) {
  delete metadata.fullCommit;
}

const target = join(repoRoot, "apps", "jobops", "lib", "generated-build-info.ts");
writeFileSync(
  target,
  `import type { JobOpsAppMetadata } from "./app-metadata-contract";\n\n` +
    `// This file is generated by scripts/generate-jobops-build-info.mjs.\n` +
    `// Do not edit by hand; rerun the build-info script instead.\n` +
    `export const GENERATED_JOBOPS_BUILD_INFO: JobOpsAppMetadata = ${JSON.stringify(metadata, null, 2)};\n`,
  "utf8"
);

console.log(`Generated ${target}`);

function resolveEnvironment() {
  const explicit = safeLabel(firstValue(
    process.env.NEXT_PUBLIC_APP_ENV,
    process.env.APP_ENV,
    process.env.JOBOPS_APP_ENV
  ));
  if (explicit) {
    return normalizeEnvironment(explicit);
  }

  const netlifyContext = safeLabel(firstValue(process.env.NETLIFY_CONTEXT, process.env.CONTEXT));
  if (netlifyContext) {
    return normalizeEnvironment(netlifyContext);
  }

  const vercelEnvironment = safeLabel(process.env.VERCEL_ENV);
  if (vercelEnvironment) {
    return normalizeEnvironment(vercelEnvironment);
  }

  return "dev";
}

function normalizeEnvironment(value) {
  const normalized = value.trim().toLowerCase();
  if (normalized === "production") {
    return "prod";
  }
  if (normalized === "development" || normalized === "local") {
    return "dev";
  }
  if (normalized === "deploy-preview" || normalized === "branch-deploy" || normalized === "preview") {
    return "preview";
  }

  return normalized || "dev";
}

function resolveCommit() {
  const deploymentCommit = safeCommit(firstValue(
    process.env.COMMIT_REF,
    process.env.NETLIFY_COMMIT_REF,
    process.env.GITHUB_SHA,
    process.env.RENDER_GIT_COMMIT,
    process.env.VERCEL_GIT_COMMIT_SHA,
    process.env.CF_PAGES_COMMIT_SHA
  ));
  if (deploymentCommit) {
    return deploymentCommit;
  }

  try {
    return safeCommit(execFileSync("git", ["rev-parse", "HEAD"], { cwd: repoRoot, encoding: "utf8" }));
  } catch {
    return undefined;
  }
}

function shortCommit(value) {
  const normalized = safeCommit(value);
  return normalized ? normalized.slice(0, 7) : "local";
}

function safeCommit(value) {
  const normalized = value?.trim();
  if (!normalized || !/^[A-Za-z0-9._-]+$/.test(normalized)) {
    return undefined;
  }

  return normalized;
}

function safeLabel(value) {
  const normalized = value?.trim();
  if (!normalized || !/^[A-Za-z0-9._-]+$/.test(normalized)) {
    return undefined;
  }

  return normalized;
}

function firstValue(...values) {
  return values.find((value) => value?.trim());
}

function findRepoRoot(startDir) {
  let current = startDir;

  while (current !== dirname(current)) {
    if (existsSync(join(current, "pnpm-workspace.yaml"))) {
      return current;
    }

    current = dirname(current);
  }

  throw new Error("Could not find JobOps repo root.");
}

function loadEnvFile(path) {
  if (!existsSync(path)) {
    return;
  }

  const contents = readFileSync(path, "utf8");
  for (const rawLine of contents.split(/\r?\n/u)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) {
      continue;
    }

    const separatorIndex = line.indexOf("=");
    if (separatorIndex === -1) {
      continue;
    }

    const key = line.slice(0, separatorIndex).trim();
    const value = unquoteEnvValue(line.slice(separatorIndex + 1).trim());
    if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) && process.env[key] === undefined) {
      process.env[key] = value;
    }
  }
}

function unquoteEnvValue(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }

  return value;
}
